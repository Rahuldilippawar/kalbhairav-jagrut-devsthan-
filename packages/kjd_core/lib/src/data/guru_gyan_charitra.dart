## २. गजमुख
आईच्या आज्ञेनुसार बालकाने भगवान शंकरांनाही आत जाऊ दिले नाही. युद्धात शिवगणांचा पराभव झाला; शेवटी शिवांनी त्रिशूलाने बालकाचे मस्तक छेदले. पार्वतीचा शोक व क्रोध पाहून शिवांनी उत्तरेकडे जाऊन पहिल्या दिसणाऱ्या प्राण्याचे मस्तक आणायला सांगितले. गजाचे मस्तक जोडून बालकाला जीवदान मिळाले. शिवांनी त्याला आपल्या गणांचा अधिपती केले – "गणपती", "गणेश".

## ३. अग्रपूजेचा मान
सर्व देवांनी वर दिला की कोणत्याही पूजेत, कार्यात प्रथम गणेशाचे पूजन होईल; अन्यथा कार्य निर्विघ्न होणार नाही. म्हणून ते "विघ्नहर्ता" आणि "विघ्नेश्वर".

## ४. आई-वडिलांची प्रदक्षिणा
एकदा शिव-पार्वतींनी स्पर्धा ठेवली – जो पृथ्वीला प्रथम प्रदक्षिणा घालून येईल तो श्रेष्ठ. कार्तिकेय मोरावर बसून निघाले. गणेशाने मात्र आई-वडिलांना आसनावर बसवून त्यांना सात प्रदक्षिणा घातल्या आणि म्हणाले, "आई-वडील हेच माझे विश्व." त्यांच्या बुद्धीवर प्रसन्न होऊन त्यांना विजयी घोषित केले. म्हणून ते "बुद्धिदाता".

## ५. एकदंत
एका कथेनुसार परशुराम शिवदर्शनाला आले असता गणेशाने त्यांना अडवले. युद्धात परशुरामांच्या परशूचा प्रहार आला; तो परशू शिवांनी दिलेला असल्याने त्याचा मान राखण्यासाठी गणेशाने तो आपल्या दातावर घेतला आणि एक दात तुटला. म्हणून ते "एकदंत".

## ६. मूषक वाहन
गजमुखासुर नावाच्या दैत्याने वराच्या बळावर देवांना त्रास दिला. गणेशाने त्याचा पराभव केला; तो मूषक बनून शरण आला आणि गणेशाचे वाहन झाला. लहानशा उंदरावर बसलेले मोठे गणपती – मोठेपणा बाह्य आकारात नसतो, हे त्याचे प्रतीक.

## ७. चंद्राला शाप
गणेशाला पडताना पाहून हसणाऱ्या चंद्राला शाप मिळाला. क्षमायाचनेनंतर शाप सौम्य झाला – भाद्रपद शुक्ल चतुर्थीला चंद्रदर्शन टाळावे आणि संकष्ट चतुर्थीला चंद्रोदयानंतर उपवास सोडावा.

## ८. महाभारताचे लेखक
महर्षी व्यासांनी महाभारत सांगण्यासाठी लेखक शोधला. गणेशाने अट घातली, "मी लिहायला थांबणार नाही." व्यासांनी अट घातली, "प्रत्येक श्लोकाचा अर्थ समजूनच लिहायचा." लिहिताना लेखणी तुटली तेव्हा गणेशाने आपलाच तुटलेला दात लेखणी म्हणून वापरला.

## ९. विविध अवतार
मुद्गल पुराणानुसार गणेशाचे आठ प्रमुख अवतार आहेत – वक्रतुंड, एकदंत, महोदर, गजानन, लंबोदर, विकट, विघ्नराज आणि धूम्रवर्ण. प्रत्येक अवताराने एका दोषरूपी असुराचा (मत्सर, मद, मोह, लोभ, क्रोध, काम, ममता, अहंकार) नाश केला. महाराष्ट्रातील अष्टविनायक ही प्रसिद्ध क्षेत्रे – मोरगाव, सिद्धटेक, पाली, महड, थेऊर, लेण्याद्री, ओझर व रांजणगाव.

