## २. लिंगोद्भव – अग्निस्तंभ
एकदा ब्रह्मदेव व विष्णू यांच्यात श्रेष्ठत्वावरून वाद झाला. तेव्हा त्यांच्यामध्ये एक अनंत अग्निस्तंभ प्रकट झाला. विष्णू वराह रूपाने त्याचे मूळ शोधायला खाली गेले आणि ब्रह्मदेव हंस रूपाने टोक शोधायला वर गेले. दोघांनाही अंत सापडला नाही. विष्णूंनी नम्रपणे हे मान्य केले; ब्रह्मदेवांनी मात्र केतकीच्या फुलाला खोटी साक्ष द्यायला लावली. तेव्हा स्तंभातून शिव प्रकट झाले. खोटेपणामुळे केतकी शिवपूजेतून वर्ज्य झाली. हा दिवस महाशिवरात्री म्हणून साजरा होतो आणि शिवलिंग पूजेचा आरंभ झाला.

## ३. सती विवाह
ब्रह्मदेवांचे पुत्र दक्ष प्रजापती यांची कन्या सती हिने कठोर तप करून शिवांना पती म्हणून प्राप्त केले. पण दक्षाला स्मशानवासी, भस्मधारी शिव आवडत नव्हते.

## ४. दक्षयज्ञ आणि सतीचा देहत्याग
दक्षाने मोठा यज्ञ केला आणि शिवांना निमंत्रण दिले नाही. शिवांनी अडवले तरी सती माहेरच्या प्रेमाने तेथे गेली. यज्ञात पतीचा अपमान ऐकून सतीने योगाग्नीत देहत्याग केला. हे कळताच शिवांच्या जटेतून वीरभद्र प्रकट झाले आणि त्यांनी यज्ञाचा विध्वंस केला. पुढे देवांच्या प्रार्थनेने शिवांनी दक्षाला बकऱ्याचे मुख लावून जीवदान दिले. सतीच्या देहाचे भाग जेथे पडले ती ५१ शक्तिपीठे झाली.

## ५. पार्वतीचे तप आणि कामदहन
सती पुढे पर्वतराज हिमवान व मेना यांच्या पोटी पार्वती म्हणून जन्मली. शिव मात्र गाढ समाधीत होते. त्या काळात तारकासुराला वर होता की फक्त शिवपुत्रच त्याचा वध करू शकेल. देवांनी शिवांची समाधी भंग करण्यासाठी कामदेवाला पाठवले. कामदेवाने बाण मारताच शिवांनी तिसरा डोळा उघडला आणि कामदेव भस्म झाला. पार्वतीने मग अन्न-पाणी सोडून कठोर तप केले – म्हणून तिला "अपर्णा" म्हणतात. शिवांनी ब्राह्मण वेशात येऊन तिची परीक्षा घेतली आणि प्रसन्न होऊन विवाहाला संमती दिली.

## ६. शिव-पार्वती विवाह व परिवार
भूत-गण, नंदी, देव-ऋषी यांच्या वरातीसह शिव-पार्वतीचा विवाह झाला. त्यांना कार्तिकेय (स्कंद) झाले, ज्यांनी तारकासुराचा वध केला. पार्वतीने घडवलेले श्री गणेश गणांचे अधिपती झाले. नंदी हे शिवांचे वाहन व द्वारपाल.

## ७. नीलकंठ – हलाहल प्राशन
समुद्रमंथनात निघालेले हलाहल विष जगाच्या रक्षणासाठी शिवांनी प्राशन केले. पार्वतीने कंठ धरल्याने ते कंठात थांबले आणि शिव "नीलकंठ" झाले.

## ८. गंगावतरण
राजा भगीरथाने पूर्वजांच्या उद्धारासाठी गंगा पृथ्वीवर आणण्याचे तप केले. गंगेचा प्रचंड वेग पृथ्वी सहन करू शकली नसती; म्हणून शिवांनी गंगा आपल्या जटांमध्ये धारण केली आणि हळूहळू पृथ्वीवर सोडली. म्हणून ते "गंगाधर".

## ९. त्रिपुरारी
तारकासुराच्या तीन पुत्रांनी आकाशात फिरणारी तीन नगरे (त्रिपुर) निर्माण करून देवांना त्रास दिला. ती तिन्ही नगरे एका रेषेत आल्यावर एकाच बाणाने नष्ट करावी लागणार होती. शिवांनी पृथ्वीचा रथ, मेरूचे धनुष्य आणि विष्णूंचा बाण करून त्रिपुराचा नाश केला. तो दिवस कार्तिक पौर्णिमा – त्रिपुरारी पौर्णिमा.

## १०. भक्तवत्सल भोळा शंकर
मार्कंडेय ऋषींना यमापासून वाचवणारे (महामृत्युंजय), रावणालाही वर देणारे, भिल्ल कन्नप्पाच्या भक्तीने प्रसन्न होणारे – असे शिव "भोळे" आहेत. बारा ज्योतिर्लिंगे ही त्यांची प्रमुख क्षेत्रे; महाराष्ट्रात भीमाशंकर, त्र्यंबकेश्वर, घृष्णेश्वर, औंढा नागनाथ व परळी वैजनाथ.

## ११. सृष्टीचा लय व पुनर्निर्मिती
कल्पाच्या शेवटी शिव तांडव नृत्य करून सृष्टीचा लय करतात आणि त्यानंतर पुन्हा नवी सृष्टी सुरू होते. म्हणून शिवाचा "शेवट" नाही – तेच शेवट आणि तेच आरंभ.

