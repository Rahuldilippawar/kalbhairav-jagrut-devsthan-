## २. काळभैरवांचे प्रकट होणे
त्या अपमानाने भगवान शंकरांच्या भ्रूमध्यातून एक तेजःपुंज, उग्र रूप प्रकट झाले. काळ्या मेघासारखा वर्ण, हातात त्रिशूल, डमरू, खड्ग व कपाल, गळ्यात मुंडमाळा, पायात घुंगरू – असे ते भयंकर पण भक्तांसाठी कृपाळू रूप होते. शंकरांनी त्यांना नाव दिले – "तू काळालाही भय उत्पन्न करणारा आहेस, म्हणून तू काळभैरव. तू पापांचे भक्षण करशील म्हणून तू पापभक्षण." ही घटना कार्तिक कृष्ण अष्टमीला घडली; म्हणून हा दिवस काळभैरव जयंती.

## ३. ब्रह्मदेवांच्या अहंकाराचे हरण
शंकरांच्या आज्ञेने काळभैरवांनी आपल्या डाव्या हाताच्या नखाने ब्रह्मदेवांचे निंदा करणारे पाचवे मुख छेदले. ब्रह्मदेवांचा अहंकार गळून पडला आणि त्यांनी शिवाची स्तुती केली. तेव्हापासून ब्रह्मदेव चतुर्मुख झाले.

## ४. ब्रह्महत्या आणि भिक्षाटन
ब्रह्मदेवांचे मुख छेदल्याने ब्रह्महत्येचे पातक लागले. ते कपाल काळभैरवांच्या हातास चिकटून राहिले आणि ब्रह्महत्या एका भयंकर स्त्रीरूपात त्यांच्या मागे लागली. लोकांना धर्माचा आदर्श दाखवण्यासाठी शंकरांनी काळभैरवांना कपाल हाती घेऊन भिक्षा मागत तीर्थाटन करण्यास सांगितले. काळभैरव कपालधारी भिक्षुक बनून तिन्ही लोक फिरले, पण कुठेही ते कपाल सुटले नाही.

## ५. काशी – कपालमोचन
शेवटी काळभैरव शिवाच्या प्रिय नगरी काशीत पोहोचले. काशीच्या पवित्र भूमीत प्रवेश करताच ब्रह्महत्या मागे राहिली आणि हातातील कपाल गळून पडले. ते स्थान "कपालमोचन तीर्थ" म्हणून प्रसिद्ध झाले. प्रायश्चित्त पूर्ण झाले.

## ६. काशीचे कोतवाल (क्षेत्रपाल)
भगवान शंकरांनी काळभैरवांना काशीचे क्षेत्रपाल – कोतवाल – नेमले. "काशीत राहणाऱ्या प्रत्येकाच्या पाप-पुण्याचा हिशेब तू ठेवशील; तुझ्या आज्ञेशिवाय कोणी येथे राहू शकणार नाही" असा अधिकार दिला. म्हणून काशीयात्रेत विश्वनाथाच्या आधी किंवा नंतर काळभैरवांचे दर्शन घेतले जाते, अन्यथा यात्रा अपूर्ण मानली जाते. यमदूतही काशीत प्रवेश करत नाहीत, कारण तेथील न्याय काळभैरव करतात – असा भाव आहे.

## ७. अष्ट भैरव व स्वरूप
काळभैरवांची आठ प्रमुख रूपे "अष्ट भैरव" म्हणून पूजली जातात – असितांग, रुरु, चंड, क्रोध, उन्मत्त, कपाल, भीषण आणि संहार भैरव. श्वान (कुत्रा) हे त्यांचे वाहन. ते दिगंबर, त्रिनेत्र व चंद्रशेखर आहेत.

## ८. महाराष्ट्रातील भैरोबा
महाराष्ट्रात काळभैरव "भैरोबा", "भैरवनाथ", "काळभैरवनाथ" नावाने गावोगावी ग्रामदैवत व कुलदैवत म्हणून पूजले जातात. अनेक ठिकाणी श्री जोगेश्वरी माता त्यांच्यासोबत पूजली जाते. गावाचे रक्षण, संकटांपासून बचाव आणि न्याय देणारे जागृत दैवत अशी त्यांची ख्याती आहे.

## ९. चिरंतन क्षेत्रपाल
काळभैरवांचा "शेवट" नाही – ते शिवस्वरूप असल्याने अनादी-अनंत आहेत. आजही प्रत्येक शिवक्षेत्राचे, प्रत्येक गावाचे आणि भक्ताचे रक्षण करणारे क्षेत्रपाल म्हणून ते जागृत आहेत. कालाष्टमी, रविवार व मंगळवार हे त्यांच्या उपासनेचे विशेष दिवस.

