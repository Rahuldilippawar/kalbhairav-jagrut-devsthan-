/// The built-in greeting for [now]: a different message each day, with the
/// title and category following the time of day (evening from 4pm).
DailyGreeting builtInGreeting(DateTime now) {
  final day = DateTime.utc(now.year, now.month, now.day).millisecondsSinceEpoch ~/ Duration.millisecondsPerDay;
  final evening = now.hour >= 16;
  return DailyGreeting(
    id: 'builtin-${dateKey(now)}',
    title: evening ? 'शुभ संध्या 🪔' : 'शुभ प्रभात 🌅',
    message: dailySubhechha[day % dailySubhechha.length],
    date: dateKey(now),
    category: evening ? 'शुभ संध्या' : 'शुभ प्रभात',
  );
}
